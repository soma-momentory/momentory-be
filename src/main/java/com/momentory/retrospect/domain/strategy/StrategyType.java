package com.momentory.retrospect.domain.strategy;

/** 이번 턴에 바바가 할 일의 굵은 방침. 이름은 기록에 남으므로 바꾸면 이전 기록과 비교할 수 없다. */
public enum StrategyType {

    /** 마무리 — 추가 질문 없이 짧게 끝맺는다. */
    CLOSE,
    /** 수정 반영 — 규칙 v6 까지의 기록에만 있다. v7 부터는 {@link #YIELD} 에 들어간다. */
    CORRECT,
    /**
     * 물러서기 — 사용자가 바바의 직전 말을 받아들이지 않았다(고쳐 말함 · 반박 · 답하기 어려워함 · 의아해함 · 다른 얘기로 넘어감).
     * 직전 질문이나 해석을 거두고 사용자가 실제로 한 말로 돌아간다.
     */
    YIELD,
    /** 공감·반영 — 말한 감정과 맥락을 받아주기만 한다. */
    REFLECT,
    /** 탐색 — 인정 한 문장 뒤에 질문 하나를 한다. 무엇을 물을지는 문장 생성 모델이 대화를 보고 정한다. */
    EXPLORE,
    /** 재해석 — 인정 한 문장 뒤에 그 생각의 근거를 함께 보는 질문을 한다. */
    REFRAME
}
